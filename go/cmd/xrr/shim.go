package main

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	xrr "hop.top/xrr"
	xexec "hop.top/xrr/adapters/exec"
)

// shimCmd is the entrypoint of every generated shim: xrr shim <run-dir> <name> [args...].
func shimCmd(args []string, stderr io.Writer) int {
	if len(args) < 2 {
		fmt.Fprintln(stderr, "usage: xrr shim <run-dir> <name> [args...] (internal; generated by 'xrr run')")
		return exitUsage
	}
	runDir, name, rest := args[0], args[1], args[2:]
	cfg, err := loadConfig(runDir)
	if err != nil {
		fmt.Fprintf(stderr, "xrr shim %s: %v\n", name, err)
		return exitUsage
	}
	rd := xrr.NewRedactor(xrr.RedactConfigFromEnv())
	return (&shim{cfg: cfg, runDir: runDir, name: name, args: rest, stderr: stderr,
		rd: rd, env: collectEnvSecrets(rd, os.Environ())}).run()
}

type shim struct {
	cfg    runConfig
	runDir string
	name   string
	args   []string
	stderr io.Writer
	rd     *xrr.Redactor
	env    envSecrets
}

func (s *shim) argv() []string { return append([]string{s.name}, s.args...) }

// safeArgv is argv as it may be shown or stored.
func (s *shim) safeArgv() []string { return s.env.scrubAll(scrubArgv(s.rd, s.argv())) }

func (s *shim) log(outcome, fp string, code int, detail string) {
	e := callEntry{Cmd: s.name, Argv: s.safeArgv(), Outcome: outcome,
		Fingerprint: fp, ExitCode: code, Detail: detail}
	if err := appendCall(s.runDir, e); err != nil {
		fmt.Fprintf(s.stderr, "xrr shim %s: log call: %v\n", s.name, err)
	}
}

func (s *shim) run() int {
	if contains(s.cfg.Deny, s.name) {
		fmt.Fprintf(s.stderr, "xrr: denied: %s (side-effect command blocked by xrr run; real binary not executed)\n",
			strings.Join(s.safeArgv(), " "))
		s.log(outDenied, "", exitDenied, "blocked, real binary not executed")
		return exitDenied
	}
	switch xrr.Mode(s.cfg.Mode) {
	case xrr.ModeRecord:
		return s.record()
	case xrr.ModeReplay:
		return s.replay()
	default:
		return s.passthrough()
	}
}

func (s *shim) passthrough() int {
	code, err := s.execReal(os.Stdin, os.Stdout, os.Stderr)
	if errors.Is(err, errNotFound) {
		return s.notFound()
	}
	s.log(outPassthrough, "", code, "")
	return code
}

func (s *shim) record() int {
	stdin := readStdin()
	var out, errb bytes.Buffer
	start := time.Now()
	code, err := s.execReal(strings.NewReader(stdin), io.MultiWriter(os.Stdout, &out), io.MultiWriter(os.Stderr, &errb))
	if errors.Is(err, errNotFound) {
		return s.notFound()
	}
	dur := time.Since(start).Milliseconds()

	// Fingerprint over the live argv; the saved copy is scrubbed. Redaction
	// never shifts a cassette key.
	req := &xexec.Request{Argv: s.argv(), Stdin: stdin}
	fp, ferr := xexec.NewAdapter().Fingerprint(req)
	if ferr != nil {
		return s.saveFailed("", code, ferr)
	}
	saved := &xexec.Request{Argv: s.safeArgv(), Stdin: s.env.scrub(stdin), Env: s.captureEnv()}
	resp := &xexec.Response{Stdout: s.env.scrub(out.String()), Stderr: s.env.scrub(errb.String()), ExitCode: code, DurationMs: dur}
	var recErr error
	if code != 0 {
		recErr = fmt.Errorf("exit status %d", code)
	}
	if err := xrr.NewFileCassette(s.cfg.CassetteDir).Save("exec", fp, saved, resp, recErr); err != nil {
		return s.saveFailed(fp, code, err)
	}
	s.log(outRecorded, fp, code, "")
	return code
}

func (s *shim) saveFailed(fp string, code int, err error) int {
	fmt.Fprintf(s.stderr, "xrr: record %s: %v\n", s.name, err)
	s.log(outError, fp, code, "cassette write failed: "+err.Error())
	return code
}

func (s *shim) replay() int {
	stdin := readStdin()
	fp, err := xexec.NewAdapter().Fingerprint(&xexec.Request{Argv: s.argv(), Stdin: stdin})
	if err != nil {
		fmt.Fprintf(s.stderr, "xrr: fingerprint %s: %v\n", s.name, err)
		s.log(outError, "", exitUsage, err.Error())
		return exitUsage
	}
	var req map[string]any
	var resp xexec.Response
	recErr, err := xrr.NewFileCassette(s.cfg.CassetteDir).Load("exec", fp, &req, &resp)
	switch {
	case errors.Is(err, xrr.ErrCassetteMiss):
		return s.miss(fp, stdin)
	case err != nil:
		fmt.Fprintf(s.stderr, "xrr: load cassette for %s: %v\n", s.name, err)
		s.log(outError, fp, exitUsage, err.Error())
		return exitUsage
	}
	io.WriteString(os.Stdout, resp.Stdout)
	io.WriteString(os.Stderr, resp.Stderr)
	code := resp.ExitCode
	if code < 0 || (code == 0 && recErr != "") {
		code = 1
	}
	s.log(outReplayed, fp, code, "")
	return code
}

func (s *shim) miss(fp, stdin string) int {
	cmdline := strings.Join(s.safeArgv(), " ")
	if !s.cfg.Strict {
		code, err := s.execReal(strings.NewReader(stdin), os.Stdout, os.Stderr)
		if errors.Is(err, errNotFound) {
			return s.notFound()
		}
		s.log(outPassthrough, fp, code, "cassette miss, --strict=false: ran real binary")
		return code
	}
	fmt.Fprintf(s.stderr, "xrr: cassette miss: %s (fingerprint %s, dir %s)\n", cmdline, fp, s.cfg.CassetteDir)
	s.log(outMiss, fp, exitMiss, "")
	return exitMiss
}

func (s *shim) notFound() int {
	fmt.Fprintf(s.stderr, "xrr: %s: real binary not found on the original PATH\n", s.name)
	s.log(outError, "", exitNotFound, "real binary not found on original PATH")
	return exitNotFound
}

func (s *shim) captureEnv() map[string]string {
	if len(s.cfg.EnvCapture) == 0 {
		return nil
	}
	m := map[string]string{}
	for _, k := range s.cfg.EnvCapture {
		if v, ok := os.LookupEnv(k); ok {
			m[k] = v
		}
	}
	return m
}

var errNotFound = errors.New("real binary not found")

// execReal runs the real binary, resolved from the PATH that existed
// before shims were prepended, and returns its exit code.
func (s *shim) execReal(in io.Reader, out, errw io.Writer) (int, error) {
	path, ok := lookPathIn(s.name, s.cfg.RealPath)
	if !ok {
		return exitNotFound, errNotFound
	}
	cmd := exec.Command(path, s.args...)
	cmd.Args[0] = s.name
	cmd.Env = withEnv(os.Environ(), "PATH", s.cfg.RealPath)
	cmd.Stdin, cmd.Stdout, cmd.Stderr = in, out, errw
	err := cmd.Run()
	var ee *exec.ExitError
	if err != nil && !errors.As(err, &ee) {
		fmt.Fprintf(s.stderr, "xrr: run %s: %v\n", path, err)
		return exitNotFound, nil
	}
	return exitCodeOf(err), nil
}

// lookPathIn finds name as an executable file in the given PATH string.
func lookPathIn(name, pathVar string) (string, bool) {
	for _, d := range filepath.SplitList(pathVar) {
		if d == "" {
			d = "."
		}
		p := filepath.Join(d, name)
		if fi, err := os.Stat(p); err == nil && !fi.IsDir() && fi.Mode()&0o111 != 0 {
			return p, true
		}
	}
	return "", false
}

// readStdin returns the shim's stdin as a string. A terminal (or /dev/null)
// reads as empty so an interactive shell never blocks on it.
func readStdin() string {
	fi, err := os.Stdin.Stat()
	if err != nil || fi.Mode()&os.ModeCharDevice != 0 {
		return ""
	}
	b, _ := io.ReadAll(os.Stdin)
	return string(b)
}
